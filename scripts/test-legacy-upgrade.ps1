$ErrorActionPreference = "Stop"

$projectRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$rolesSqlPath = Join-Path $projectRoot "docker/postgres-init/10-least-privilege.sql"
$callbackSqlPath = Join-Path $projectRoot "src/main/resources/db/migration/beforeMigrate.sql"
$v2SqlPath = Join-Path $projectRoot "src/main/resources/db/migration/V2__optimistic_lock_and_indexes.sql"

foreach ($requiredPath in @($rolesSqlPath, $callbackSqlPath, $v2SqlPath)) {
    if (-not (Test-Path -LiteralPath $requiredPath)) {
        throw "No se encontró el archivo requerido: $requiredPath"
    }
}

$testContainer = "climapolar-legacy-upgrade-$PID-$([Guid]::NewGuid().ToString('N').Substring(0, 8))"
$oldPassword = "legacy-password-only-for-test"
$desiredPassword = "desired-password-only-for-test"
$containerStarted = $false

try {
    docker run --detach --rm --name $testContainer `
        --tmpfs "/var/lib/postgresql/data:rw,nosuid,nodev,size=256m" `
        --env "POSTGRES_DB=frio_polar" `
        --env "POSTGRES_USER=frio_polar" `
        --env "POSTGRES_PASSWORD=$oldPassword" `
        postgres:16-alpine | Out-Null
    if ($LASTEXITCODE -ne 0) {
        throw "No se pudo iniciar el PostgreSQL efímero de prueba."
    }
    $containerStarted = $true

    $ready = $false
    for ($attempt = 0; $attempt -lt 60; $attempt++) {
        # The image briefly starts a socket-only server during initialization.
        # Requiring TCP avoids racing that temporary process before the final
        # PostgreSQL server is listening.
        docker exec $testContainer pg_isready -h 127.0.0.1 -U frio_polar -d frio_polar *> $null
        if ($LASTEXITCODE -eq 0) {
            $ready = $true
            break
        }
        Start-Sleep -Milliseconds 500
    }
    if (-not $ready) {
        throw "PostgreSQL no quedó disponible para la prueba."
    }

    $legacySchema = @'
CREATE TABLE trabajos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    descripcion VARCHAR(2000) NOT NULL,
    tipo_servicio VARCHAR(255) NOT NULL,
    ubicacion VARCHAR(255) NOT NULL,
    fecha DATE NOT NULL,
    imagen_url VARCHAR(1000) NOT NULL,
    video_url VARCHAR(1000),
    destacado BOOLEAN NOT NULL
);
INSERT INTO trabajos (
    titulo, descripcion, tipo_servicio, ubicacion, fecha, imagen_url, destacado
) VALUES (
    'Trabajo legacy', 'Fila que debe sobrevivir al upgrade', 'Instalación',
    'Buenos Aires', DATE '2026-08-17', 'https://example.test/legacy.jpg', TRUE
);
'@
    $legacySchema | docker exec -i $testContainer `
        psql -X -v ON_ERROR_STOP=1 -U frio_polar -d frio_polar
    if ($LASTEXITCODE -ne 0) {
        throw "No se pudo preparar el esquema legacy de prueba."
    }

    Get-Content -Raw -Encoding UTF8 -LiteralPath $rolesSqlPath |
        docker exec --env "POSTGRES_PASSWORD=$desiredPassword" -i $testContainer `
            psql -X -v ON_ERROR_STOP=1 -U frio_polar -d frio_polar
    if ($LASTEXITCODE -ne 0) {
        throw "La migración de credenciales falló en el escenario legacy."
    }

    # The callback must be harmless when Flyway invokes it again on a later
    # startup, so execute it twice before applying V2.
    for ($execution = 0; $execution -lt 2; $execution++) {
        Get-Content -Raw -Encoding UTF8 -LiteralPath $callbackSqlPath |
            docker exec --env "PGPASSWORD=$desiredPassword" -i $testContainer `
                psql -X -w -h 127.0.0.1 -v ON_ERROR_STOP=1 `
                    -U climapolar_app -d frio_polar
        if ($LASTEXITCODE -ne 0) {
            throw "El callback beforeMigrate falló en la ejecución $($execution + 1)."
        }
    }

    Get-Content -Raw -Encoding UTF8 -LiteralPath $v2SqlPath |
        docker exec --env "PGPASSWORD=$desiredPassword" -i $testContainer `
            psql -X -w -h 127.0.0.1 -v ON_ERROR_STOP=1 `
                -U climapolar_app -d frio_polar
    if ($LASTEXITCODE -ne 0) {
        throw "V2 no pudo ejecutarse después de preparar el esquema legacy."
    }

    $verificationSql = @'
SELECT
    (to_regclass('public.trabajo_medios') IS NOT NULL)::text || '|' ||
    (to_regclass('public.configuracion_aplicacion') IS NOT NULL)::text || '|' ||
    EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = 'trabajos' AND column_name = 'version'
    )::text || '|' ||
    (SELECT count(*) FROM trabajos WHERE titulo = 'Trabajo legacy')::text || '|' ||
    (SELECT version FROM trabajos WHERE titulo = 'Trabajo legacy')::text || '|' ||
    (
        SELECT count(*) FROM pg_indexes
         WHERE schemaname = 'public'
           AND indexname IN (
               'idx_trabajos_fecha_id',
               'idx_trabajos_categoria_fecha_id',
               'idx_trabajos_destacados_fecha_id',
               'idx_trabajo_medios_trabajo_orden'
           )
    )::text;
'@
    $verification = $verificationSql |
        docker exec --env "PGPASSWORD=$desiredPassword" -i $testContainer `
            psql -X -w -h 127.0.0.1 -U climapolar_app -d frio_polar -At
    if ($LASTEXITCODE -ne 0) {
        throw "No se pudo verificar el resultado del upgrade."
    }
    if (($verification -join "`n").Trim() -ne "true|true|true|1|0|4") {
        throw "El esquema resultante no coincide con lo esperado: $verification"
    }

    Write-Host "OK: upgrade legacy, callback idempotente y nueva credencial verificados."
} finally {
    if ($containerStarted) {
        docker rm --force $testContainer *> $null
    }
}
