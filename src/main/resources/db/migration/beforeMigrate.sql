-- Flyway baselines an existing legacy schema at V1. The first version of the
-- application only had `trabajos`, so V1 is intentionally skipped there and
-- these two tables must exist before V2 creates its indexes.
DO $$
BEGIN
    IF to_regclass('public.trabajos') IS NOT NULL THEN
        IF to_regclass('public.trabajo_medios') IS NULL THEN
            CREATE TABLE IF NOT EXISTS public.trabajo_medios (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                trabajo_id BIGINT NOT NULL,
                tipo VARCHAR(16) NOT NULL,
                ruta_publica VARCHAR(1000) NOT NULL,
                ruta_miniatura VARCHAR(1000),
                nombre_original VARCHAR(255),
                content_type VARCHAR(100),
                tamano_bytes BIGINT,
                orden INTEGER NOT NULL,
                gestionado BOOLEAN NOT NULL,
                CONSTRAINT fk_trabajo_medios_trabajo
                    FOREIGN KEY (trabajo_id) REFERENCES public.trabajos(id),
                CONSTRAINT trabajo_medios_tipo_check
                    CHECK (tipo IN ('IMAGEN', 'VIDEO'))
            );
        END IF;

        IF to_regclass('public.configuracion_aplicacion') IS NULL THEN
            CREATE TABLE IF NOT EXISTS public.configuracion_aplicacion (
                clave VARCHAR(100) PRIMARY KEY,
                valor VARCHAR(255) NOT NULL
            );
        END IF;
    END IF;
END
$$;
