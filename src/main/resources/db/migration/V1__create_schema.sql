CREATE TABLE trabajos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    descripcion VARCHAR(2000) NOT NULL,
    tipo_servicio VARCHAR(255) NOT NULL,
    ubicacion VARCHAR(255) NOT NULL,
    fecha DATE NOT NULL,
    imagen_url VARCHAR(1000) NOT NULL,
    video_url VARCHAR(1000),
    destacado BOOLEAN NOT NULL
);

CREATE TABLE trabajo_medios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trabajo_id BIGINT NOT NULL,
    tipo VARCHAR(16) NOT NULL,
    ruta_publica VARCHAR(1000) NOT NULL,
    ruta_miniatura VARCHAR(1000),
    nombre_original VARCHAR(255),
    content_type VARCHAR(100),
    tamano_bytes BIGINT,
    orden INTEGER NOT NULL,
    gestionado BOOLEAN NOT NULL,
    CONSTRAINT fk_trabajo_medios_trabajo
        FOREIGN KEY (trabajo_id) REFERENCES trabajos(id),
    CONSTRAINT trabajo_medios_tipo_check
        CHECK (tipo IN ('IMAGEN', 'VIDEO'))
);

CREATE TABLE configuracion_aplicacion (
    clave VARCHAR(100) PRIMARY KEY,
    valor VARCHAR(255) NOT NULL
);
